from __future__ import annotations
import glob
from pathlib import Path
import pandas as pd

REPO = Path("/home/user/Pure-space-Branding")
WORK = REPO / "01_市調與定位/working"
COMP = WORK / "competitors.csv"
PAST_XLSX = "/root/.claude/uploads/e302ebbd-cdc7-4ddc-87db-9a1c9f50b92b/99ffdb92-___________.xlsx"
OUT_MD = WORK / "新推案市場分析_壯圍千萬透天_v0.1.md"
LVR_DIR = "/tmp/lvr"
M2_PER_PING = 3.305785
