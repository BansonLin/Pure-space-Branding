# 新案參數（取自 DWG：壯圍鄉五權段789.790，27戶，透天3層）
NEW = dict(
    區="壯圍鄉", 戶數=27, 樓層="地上3層+屋頂", 建坪區間=(38, 43),
    地坪區間_坪=(72/M2_PER_PING, 123/M2_PER_PING), 用途="H-2住家用",
    目標="千萬內(總價<1000萬)", 建蔽率="60%", 設計="富彥建築師事務所",
)


def load_past():
    df = pd.read_excel(PAST_XLSX, sheet_name="鼎弘建案總表", header=None)
    rows = {}
    for _, r in df.iterrows():
        key = str(r[0])
        if key != "nan":
            rows[key] = [str(r[i]) if str(r[i]) != "nan" else "" for i in (1, 2, 3)]
    detail = pd.read_excel(PAST_XLSX, sheet_name="玉田森活1_逐戶實登(30筆)", header=0)
    detail.columns = ["門牌", "交易日民國", "總價萬", "建坪", "單價萬坪", "房", "廳", "衛"]
    detail = detail.dropna(subset=["總價萬"])
    return rows, detail


def main():
    comp = pd.read_csv(COMP)
    past_rows, yt1 = load_past()

    zw = comp[comp["鄉鎮市區"] == "壯圍鄉"].sort_values("戶數", ascending=False)
    # 千萬內定位帶 (總價中位 < 1050 視為同帶競品)
    sub10_zw = zw[zw["總價_萬_中位"] < 1050]
    # 鄰區千萬內 (五結)
    wj = comp[(comp["鄉鎮市區"] == "五結鄉") & (comp["總價_萬_中位"] < 1050)].sort_values("戶數", ascending=False)

    md = []
    A = md.append
    A("# 新推案市場分析 — 壯圍「千萬內」透天\n")
    A(f"> 製表：璞域市場資料｜資料截止：{CUTOFF}｜來源：內政部實價登錄 + 鼎弘自有推案資料 + 591 交叉")
    A("> 本報告為**開放資料 + 業主提供**之分析；預售競品來自實價登錄揭露案名，建商名未揭露者以「—」表示。\n")

    # ── 0. 摘要
    A("## 0. 一頁摘要（給決策用）\n")
    A("| 項目 | 結論 |")
    A("|------|------|")
    A("| **新案定位** | 壯圍鄉五權段，27 戶，透天 3 層，建坪 38~43 坪，目標總價**千萬內** |")
    A("| **市場可行性** | ✅ 高度可行。壯圍預售透天**中位總價落在 858~1,238 萬**，最大量體案（宗硯大砌 31 戶）正以 **858 萬** 銷售 |")
